//! Project the published `a4aa-claude` card, launch spec and mechanism dialect
//! into the constants this package compiles against.
//!
//! This is a build-time bridge, not a second declaration. Every fact is read
//! from the published crate on every build, and the build fails when the card
//! stops carrying a fact this Agent's launch mapping depends on. The dependency
//! stays in the build graph so `a4aa`'s async ACP runtime feature set neither
//! replaces the client's synchronous process owner nor changes the client's
//! `serde_json` ordering.

use a4aa::card::AgentSurface;
use a4aa::dialect::{CommandSurface, McpSurface, SubagentSurface};
use a4aa::{LaneSpec, ModelCatalog};
use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::PathBuf;

/// The flag that precedes one placeholder in the published argument template.
fn flag_before<'a>(args: &'a [&'a str], placeholder: &str) -> Option<&'a str> {
    args.windows(2)
        .find(|pair| pair[1] == placeholder)
        .map(|pair| pair[0])
}

fn main() {
    println!("cargo:rerun-if-changed=build.rs");

    let card = a4aa_claude::card();
    let spec = a4aa_claude::spec();
    let dialect = a4aa_claude::dialect();

    let AgentSurface::Cli(cli) = &card.surface else {
        panic!("the published Claude card's primary lane is not CLI");
    };
    let LaneSpec::Cli(_) = &spec.lane else {
        panic!("the published Claude spec does not materialize the CLI lane");
    };
    assert_eq!(
        card.id, dialect.id,
        "the card and its mechanism dialect disagree on the Agent id"
    );
    assert_eq!(
        spec.command.program, card.detect.binaries[0],
        "the launch program is not the detected binary"
    );

    // The published template opens with fixed stream-json flags and then
    // appends per-turn flags. LicoUp builds the same argv from a fixed prefix
    // plus its own optional selections, so the prefix is everything before the
    // first placeholder.
    let first_placeholder = cli
        .args
        .iter()
        .position(|arg| arg.contains('{'))
        .expect("the published Claude template carries per-turn placeholders");
    // A placeholder is introduced by the flag before it, so the fixed prefix
    // ends before that flag rather than including it.
    let fixed_prefix_end = first_placeholder
        .checked_sub(1)
        .expect("the first placeholder is introduced by a flag");
    let fixed_args = &cli.args[..fixed_prefix_end];
    assert!(
        fixed_args.iter().all(|arg| !arg.contains('{')),
        "the fixed stream prefix must not carry a placeholder"
    );
    assert!(
        cli.args[fixed_prefix_end].starts_with("--"),
        "the fixed prefix must stop immediately before the first per-turn flag"
    );

    let model_flag = flag_before(cli.args, "{model}").expect("the card declares --model");
    let effort_flag = flag_before(cli.args, "{effort}").expect("the card declares --effort");
    let permission_flag =
        flag_before(cli.args, "{permission}").expect("the card declares --permission-mode");
    let instructions_flag =
        flag_before(cli.args, "{instructions}").expect("the card declares its guidance flag");
    let resume_flag = cli
        .resume_args
        .windows(2)
        .find(|pair| pair[1] == "{sessionId}")
        .map(|pair| pair[0])
        .expect("the card declares the resume flag");

    assert!(
        matches!(card.features.models, ModelCatalog::None),
        "the published Claude card now declares a model catalog LicoUp does not read"
    );

    let commands = match dialect.commands {
        CommandSurface::MarkdownDir(dir)
        | CommandSurface::PromptDir(dir)
        | CommandSurface::TomlDir(dir)
        | CommandSurface::SkillDir(dir) => Some(dir),
        CommandSurface::None => None,
    };
    let subagents = match dialect.subagents {
        SubagentSurface::MarkdownDir(dir)
        | SubagentSurface::CodexToml(dir)
        | SubagentSurface::KiroJson(dir) => Some(dir),
        SubagentSurface::None => None,
    };
    let (mcp_file, mcp_key, mcp_adapted) = match dialect.mcp {
        McpSurface::JsonMerge {
            file, key, adapted, ..
        } => (Some(file), Some(key), adapted),
        McpSurface::None => (None, None, false),
    };

    let mut generated = String::new();
    writeln!(
        generated,
        "// @generated by crates/licoup-agent-claude-code/build.rs from the published a4aa-claude card."
    )
    .unwrap();
    writeln!(
        generated,
        "// Do not edit; edit the build projection instead."
    )
    .unwrap();
    macro_rules! string {
        ($name:literal, $value:expr) => {
            writeln!(generated, "pub const {}: &str = {:?};", $name, $value).unwrap();
        };
    }
    macro_rules! optional_string {
        ($name:literal, $value:expr) => {
            writeln!(
                generated,
                "pub const {}: Option<&str> = {:?};",
                $name, $value
            )
            .unwrap();
        };
    }
    macro_rules! boolean {
        ($name:literal, $value:expr) => {
            writeln!(generated, "pub const {}: bool = {:?};", $name, $value).unwrap();
        };
    }
    macro_rules! strings {
        ($name:literal, $values:expr) => {{
            write!(generated, "pub const {}: &[&str] = &[", $name).unwrap();
            for value in $values {
                write!(generated, "{value:?}, ").unwrap();
            }
            generated.push_str("];\n");
        }};
    }

    string!("UPSTREAM_CARD_ID", card.id);
    string!("UPSTREAM_CARD_LABEL", card.label);
    string!("UPSTREAM_PROGRAM", spec.command.program);
    strings!("UPSTREAM_LAUNCH_TEMPLATE", cli.args.iter());
    strings!("UPSTREAM_FIXED_ARGS", fixed_args.iter());
    string!("UPSTREAM_LANE_KIND", "cli");
    string!("UPSTREAM_MODEL_FLAG", model_flag);
    string!("UPSTREAM_EFFORT_FLAG", effort_flag);
    string!("UPSTREAM_PERMISSION_FLAG", permission_flag);
    string!("UPSTREAM_INSTRUCTIONS_FLAG", instructions_flag);
    string!("UPSTREAM_RESUME_FLAG", resume_flag);
    strings!("UPSTREAM_PERMISSION_MODES", card.features.permission_modes);
    optional_string!(
        "UPSTREAM_PERMISSION_DEFAULT",
        card.features.permission_default
    );
    optional_string!("UPSTREAM_SKILLS_DIR", dialect.skills_dir);
    optional_string!(
        "UPSTREAM_RULES_FILE",
        dialect.rules.as_ref().map(|target| target.path)
    );
    optional_string!("UPSTREAM_COMMANDS_DIR", commands);
    optional_string!("UPSTREAM_SUBAGENTS_DIR", subagents);
    optional_string!("UPSTREAM_MCP_FILE", mcp_file);
    optional_string!("UPSTREAM_MCP_KEY", mcp_key);
    boolean!("UPSTREAM_MCP_ADAPTED", mcp_adapted);
    boolean!("UPSTREAM_NATIVE_PROFILES", dialect.native_profiles);
    // The parser classifies these fields by name, so the card must keep
    // declaring them; a missing fact fails the build rather than silently
    // scanning the wrong key.
    let session_id_field = cli
        .session_id_path
        .expect("the published Claude card declares the session id field");
    let result_field = cli
        .result_path
        .expect("the published Claude card declares the result text field");
    // The parser reads these against the top-level event object. A dotted path
    // would mean a nested carrier this reader must learn, so fail the build
    // instead of silently reading the wrong key.
    assert!(
        !session_id_field.contains('.') && !result_field.contains('.'),
        "the published Claude card moved a top-level field into a nested path"
    );
    string!("UPSTREAM_SESSION_ID_FIELD", session_id_field);
    string!(
        "UPSTREAM_RESULT_SELECTOR",
        cli.result_selector
            .expect("the published Claude card declares the result selector")
    );
    string!("UPSTREAM_RESULT_FIELD", result_field);
    string!(
        "UPSTREAM_STDIN_TEMPLATE",
        cli.stdin_template
            .as_ref()
            .expect("the published Claude card declares the stdin template")
            .to_string()
    );
    optional_string!(
        "UPSTREAM_LIVE_USAGE_EVENT",
        card.usage.live.as_ref().map(|usage| usage.event)
    );
    optional_string!(
        "UPSTREAM_LIVE_USAGE_PATH",
        card.usage.live.as_ref().map(|usage| usage.path)
    );
    string!(
        "UPSTREAM_TRANSCRIPT_ROOT",
        card.usage
            .transcript
            .as_ref()
            .expect("the published Claude card declares a transcript store")
            .root
    );
    boolean!("UPSTREAM_EFFORT", card.features.effort);
    boolean!("UPSTREAM_STEER", card.features.steer);

    let out = PathBuf::from(env::var_os("OUT_DIR").expect("cargo sets OUT_DIR"));
    fs::write(out.join("claude_dialect.rs"), generated)
        .expect("write generated Claude dialect facts");
}
