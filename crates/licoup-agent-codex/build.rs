//! Project the published `a4aa-codex` card, launch spec and mechanism dialect
//! into the constants this package compiles against.
//!
//! This is a build-time bridge, not a second declaration. Every fact is read
//! from the published crate on every build, and the build fails when the card
//! stops carrying a fact this Agent's driver and parser depend on. The
//! dependency stays in the build graph so `a4aa`'s async ACP runtime feature set
//! neither replaces the client's synchronous process owner nor changes the
//! client's `serde_json` ordering.

use a4aa::card::AgentSurface;
use a4aa::dialect::{CommandSurface, McpSurface, SubagentSurface};
use a4aa::{LaneSpec, ModelCatalog};
use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::PathBuf;

fn main() {
    println!("cargo:rerun-if-changed=build.rs");

    let card = a4aa_codex::card();
    let spec = a4aa_codex::spec();
    let dialect = a4aa_codex::dialect();

    let AgentSurface::Rpc(rpc) = &card.surface else {
        panic!("the published Codex card's primary lane is not RPC");
    };
    let LaneSpec::Rpc(_) = &spec.lane else {
        panic!("the published Codex spec does not materialize the RPC lane");
    };
    assert_eq!(
        card.id, dialect.id,
        "the card and its mechanism dialect disagree on the Agent id"
    );
    assert_eq!(
        spec.command.program, card.detect.binaries[0],
        "the launch program is not the detected binary"
    );
    assert_eq!(
        spec.command.args,
        rpc.spawn_args
            .iter()
            .map(|arg| (*arg).to_string())
            .collect::<Vec<_>>(),
        "the materialized launch args disagree with the card's RPC surface"
    );

    let initialize = rpc
        .initialize
        .as_ref()
        .expect("the Codex card declares initialize")
        .method;
    let session_open = rpc
        .session_open
        .as_ref()
        .expect("the Codex card declares the thread-open call")
        .method;
    let session_resume = rpc
        .session_resume
        .as_ref()
        .expect("the Codex card declares thread/resume")
        .method;
    let prompt = rpc.prompt.method;
    let cancel = rpc
        .cancel
        .as_ref()
        .expect("the Codex card declares turn/interrupt")
        .method;
    let completion = rpc
        .completion
        .as_ref()
        .expect("the Codex card declares turn/completed");
    let completion_status_field = completion
        .status_path
        .expect("the Codex card declares the completion status path")
        .rsplit('.')
        .next()
        .expect("the status path carries a final field");
    let completion_turn_field = completion
        .turn_id_path
        .expect("the Codex card declares the completion turn path")
        .rsplit('.')
        .next()
        .expect("the turn path carries a final field");
    let initialized = rpc
        .initialized
        .expect("the Codex card declares the initialized notification");
    let text_event = rpc
        .text_event_method
        .expect("the Codex card declares the streamed-text method");
    let model_list = match card.features.models {
        ModelCatalog::RpcMethod(method) => method,
        ModelCatalog::None | ModelCatalog::CliArgs(_) => {
            panic!("the published Codex card no longer enumerates models over RPC")
        }
    };

    // These are passthrough calls this package issues by name rather than
    // through the generic request vocabulary. The card lists them, so a card
    // that stops declaring one fails the build instead of drifting silently.
    let passthrough = |method: &'static str| {
        assert!(
            rpc.passthrough.contains(&method),
            "the published Codex card no longer declares passthrough method {method}"
        );
        method
    };
    let rate_limits = passthrough("account/rateLimits/read");
    let unarchive = passthrough("thread/unarchive");
    let steer = passthrough("turn/steer");

    let commands = match dialect.commands {
        CommandSurface::PromptDir(dir)
        | CommandSurface::MarkdownDir(dir)
        | CommandSurface::TomlDir(dir)
        | CommandSurface::SkillDir(dir) => Some(dir),
        CommandSurface::None => None,
    };
    let subagents = match dialect.subagents {
        SubagentSurface::CodexToml(dir)
        | SubagentSurface::MarkdownDir(dir)
        | SubagentSurface::KiroJson(dir) => Some(dir),
        SubagentSurface::None => None,
    };
    let (mcp_file, mcp_key, mcp_adapted) = match dialect.mcp {
        McpSurface::JsonMerge {
            file, key, adapted, ..
        } => (Some(file), Some(key), adapted),
        McpSurface::None => (None, None, false),
    };

    let mut generated = String::new();
    writeln!(
        generated,
        "// @generated by crates/licoup-agent-codex/build.rs from the published a4aa-codex card."
    )
    .unwrap();
    writeln!(
        generated,
        "// Do not edit; edit the build projection instead."
    )
    .unwrap();
    macro_rules! string {
        ($name:literal, $value:expr) => {
            writeln!(generated, "pub const {}: &str = {:?};", $name, $value).unwrap();
        };
    }
    macro_rules! optional_string {
        ($name:literal, $value:expr) => {
            writeln!(
                generated,
                "pub const {}: Option<&str> = {:?};",
                $name, $value
            )
            .unwrap();
        };
    }
    macro_rules! boolean {
        ($name:literal, $value:expr) => {
            writeln!(generated, "pub const {}: bool = {:?};", $name, $value).unwrap();
        };
    }
    macro_rules! strings {
        ($name:literal, $values:expr) => {{
            write!(generated, "pub const {}: &[&str] = &[", $name).unwrap();
            for value in $values {
                write!(generated, "{value:?}, ").unwrap();
            }
            generated.push_str("];\n");
        }};
    }

    string!("UPSTREAM_CARD_ID", card.id);
    string!("UPSTREAM_CARD_LABEL", card.label);
    string!("UPSTREAM_PROGRAM", spec.command.program);
    strings!(
        "UPSTREAM_LAUNCH_ARGS",
        spec.command.args.iter().map(String::as_str)
    );
    string!("UPSTREAM_LANE_KIND", "rpc");
    strings!("UPSTREAM_PERMISSION_MODES", card.features.permission_modes);
    optional_string!(
        "UPSTREAM_PERMISSION_DEFAULT",
        card.features.permission_default
    );
    optional_string!("UPSTREAM_SKILLS_DIR", dialect.skills_dir);
    optional_string!(
        "UPSTREAM_RULES_FILE",
        dialect.rules.as_ref().map(|target| target.path)
    );
    optional_string!("UPSTREAM_COMMANDS_DIR", commands);
    optional_string!("UPSTREAM_SUBAGENTS_DIR", subagents);
    optional_string!("UPSTREAM_MCP_FILE", mcp_file);
    optional_string!("UPSTREAM_MCP_KEY", mcp_key);
    boolean!("UPSTREAM_MCP_ADAPTED", mcp_adapted);
    boolean!("UPSTREAM_NATIVE_PROFILES", dialect.native_profiles);

    string!("UPSTREAM_INITIALIZE_METHOD", initialize);
    string!("UPSTREAM_INITIALIZED_METHOD", initialized);
    string!("UPSTREAM_SESSION_OPEN_METHOD", session_open);
    string!("UPSTREAM_SESSION_RESUME_METHOD", session_resume);
    string!("UPSTREAM_PROMPT_METHOD", prompt);
    string!("UPSTREAM_CANCEL_METHOD", cancel);
    string!("UPSTREAM_TEXT_EVENT_METHOD", text_event);
    string!("UPSTREAM_COMPLETION_METHOD", completion.method);
    string!("UPSTREAM_COMPLETION_STATUS_FIELD", completion_status_field);
    string!("UPSTREAM_COMPLETION_TURN_FIELD", completion_turn_field);
    string!("UPSTREAM_MODEL_LIST_METHOD", model_list);
    string!("UPSTREAM_RATE_LIMITS_METHOD", rate_limits);
    string!("UPSTREAM_UNARCHIVE_METHOD", unarchive);
    string!("UPSTREAM_STEER_METHOD", steer);
    string!(
        "UPSTREAM_SESSION_SCOPE",
        format!("{:?}", rpc.session_scope).to_lowercase()
    );
    boolean!("UPSTREAM_KILL_ON_CANCEL", rpc.kill_on_cancel);
    optional_string!(
        "UPSTREAM_INSTRUCTIONS_PARAM",
        match card.features.instructions {
            a4aa::InstructionChannel::Param(name) => Some(name),
            a4aa::InstructionChannel::Compose | a4aa::InstructionChannel::Flag(_) => None,
        }
    );
    optional_string!(
        "UPSTREAM_INSTRUCTIONS_FLAG",
        match card.features.instructions {
            a4aa::InstructionChannel::Flag(flag) => Some(flag),
            a4aa::InstructionChannel::Compose | a4aa::InstructionChannel::Param(_) => None,
        }
    );

    let out = PathBuf::from(env::var_os("OUT_DIR").expect("cargo sets OUT_DIR"));
    fs::write(out.join("codex_dialect.rs"), generated)
        .expect("write generated Codex dialect facts");
}
