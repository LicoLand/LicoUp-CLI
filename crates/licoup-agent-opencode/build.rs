//! Project the published `a4aa-opencode` card and mechanism dialect into the
//! constants this package compiles against.
//!
//! This is a build-time bridge, not a second declaration. Every fact is read
//! from the published crate on every build, and the build fails when the card
//! stops carrying the serve/ACP surface this Agent's engine and driver depend
//! on. The dependency stays in the build graph so `a4aa`'s async runtime
//! neither replaces the client's synchronous serve engine nor changes the
//! client's `serde_json` ordering.

use a4aa::card::AgentSurface;
use a4aa::dialect::{CommandSurface, McpSurface, SubagentSurface};
use a4aa::{LaneSpec, ModelCatalog};
use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::PathBuf;

fn main() {
    println!("cargo:rerun-if-changed=build.rs");

    let card = a4aa_opencode::card();
    let spec = a4aa_opencode::spec();
    let dialect = a4aa_opencode::dialect();

    let AgentSurface::Serve { spawn_args } = &card.surface else {
        panic!("the published OpenCode card's primary lane is not the serve surface");
    };
    let LaneSpec::Serve { .. } = &spec.lane else {
        panic!("the published OpenCode spec does not materialize the serve lane");
    };
    assert_eq!(
        card.id, dialect.id,
        "the card and its mechanism dialect disagree on the Agent id"
    );
    assert_eq!(
        spec.command.program, card.detect.binaries[0],
        "the launch program is not the detected binary"
    );

    // The card starts the server with `serve --port 0` and lets the lane read
    // the announced endpoint. LicoUp's engine owns port selection itself and
    // passes an explicit `--hostname` / `--port`, so only the subcommand is a
    // fact this package can take from the card; the rest is the host's
    // endpoint policy and is declared in `crate::policy`.
    let serve_subcommand = spawn_args
        .first()
        .expect("the published OpenCode serve surface names its subcommand");
    assert!(
        !serve_subcommand.contains('{'),
        "the serve subcommand must be a fixed word, not a template"
    );

    let acp_alternate = card
        .alternates
        .iter()
        .find_map(|alternate| match &alternate.surface {
            AgentSurface::Acp {
                prefer_load,
                spawn_args,
                ..
            } => Some((*prefer_load, *spawn_args)),
            _ => None,
        });
    let (prefer_load, acp_spawn_args) =
        acp_alternate.expect("the published OpenCode card declares its ACP alternate");
    let acp_subcommand = acp_spawn_args
        .first()
        .expect("the published OpenCode ACP surface names its subcommand");

    let commands = match dialect.commands {
        CommandSurface::MarkdownDir(dir)
        | CommandSurface::PromptDir(dir)
        | CommandSurface::TomlDir(dir)
        | CommandSurface::SkillDir(dir) => Some(dir),
        CommandSurface::None => None,
    };
    let subagents = match dialect.subagents {
        SubagentSurface::MarkdownDir(dir)
        | SubagentSurface::CodexToml(dir)
        | SubagentSurface::KiroJson(dir) => Some(dir),
        SubagentSurface::None => None,
    };
    let (mcp_file, mcp_key, mcp_adapted) = match dialect.mcp {
        McpSurface::JsonMerge {
            file, key, adapted, ..
        } => (Some(file), Some(key), adapted),
        McpSurface::None => (None, None, false),
    };
    let models = match card.features.models {
        ModelCatalog::None => None,
        ModelCatalog::RpcMethod(method) => Some(method),
        ModelCatalog::CliArgs(_) => None,
    };

    let mut generated = String::new();
    writeln!(
        generated,
        "// @generated by crates/licoup-agent-opencode/build.rs from the published a4aa-opencode card."
    )
    .unwrap();
    writeln!(
        generated,
        "// Do not edit; edit the build projection instead."
    )
    .unwrap();
    macro_rules! string {
        ($name:literal, $value:expr) => {
            writeln!(generated, "pub const {}: &str = {:?};", $name, $value).unwrap();
        };
    }
    macro_rules! optional_string {
        ($name:literal, $value:expr) => {
            writeln!(
                generated,
                "pub const {}: Option<&str> = {:?};",
                $name, $value
            )
            .unwrap();
        };
    }
    macro_rules! boolean {
        ($name:literal, $value:expr) => {
            writeln!(generated, "pub const {}: bool = {:?};", $name, $value).unwrap();
        };
    }
    macro_rules! strings {
        ($name:literal, $values:expr) => {{
            write!(generated, "pub const {}: &[&str] = &[", $name).unwrap();
            for value in $values {
                write!(generated, "{value:?}, ").unwrap();
            }
            generated.push_str("];\n");
        }};
    }

    string!("UPSTREAM_CARD_ID", card.id);
    string!("UPSTREAM_CARD_LABEL", card.label);
    string!("UPSTREAM_PROGRAM", spec.command.program);
    strings!("UPSTREAM_SERVE_SPAWN_ARGS", spawn_args.iter());
    string!("UPSTREAM_SERVE_SUBCOMMAND", serve_subcommand);
    string!("UPSTREAM_ACP_SUBCOMMAND", acp_subcommand);
    boolean!("UPSTREAM_ACP_PREFER_LOAD", prefer_load);
    string!("UPSTREAM_LANE_KIND", "serve");
    strings!("UPSTREAM_PERMISSION_MODES", card.features.permission_modes);
    optional_string!(
        "UPSTREAM_PERMISSION_DEFAULT",
        card.features.permission_default
    );
    optional_string!("UPSTREAM_SKILLS_DIR", dialect.skills_dir);
    optional_string!(
        "UPSTREAM_RULES_FILE",
        dialect.rules.as_ref().map(|target| target.path)
    );
    optional_string!("UPSTREAM_COMMANDS_DIR", commands);
    optional_string!("UPSTREAM_SUBAGENTS_DIR", subagents);
    optional_string!("UPSTREAM_MCP_FILE", mcp_file);
    optional_string!("UPSTREAM_MCP_KEY", mcp_key);
    boolean!("UPSTREAM_MCP_ADAPTED", mcp_adapted);
    boolean!("UPSTREAM_NATIVE_PROFILES", dialect.native_profiles);
    optional_string!("UPSTREAM_MODELS_METHOD", models);
    optional_string!(
        "UPSTREAM_LIVE_USAGE_EVENT",
        card.usage.live.as_ref().map(|usage| usage.event)
    );
    optional_string!(
        "UPSTREAM_LIVE_USAGE_PATH",
        card.usage.live.as_ref().map(|usage| usage.path)
    );

    let out = PathBuf::from(env::var_os("OUT_DIR").expect("cargo sets OUT_DIR"));
    fs::write(out.join("opencode_dialect.rs"), generated)
        .expect("write generated OpenCode dialect facts");
}
