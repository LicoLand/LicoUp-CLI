//! The host side of Agent execution: the work-context seam, the adapter
//! registry and the adapter execution that drives them, the ACP session
//! transport, and the local service control plane.
//!
//! What this crate owns:
//!
//! * the work-context seam — the binding contract, the adapter transport, the
//!   production host driver and the C01 effect port over them, in [`effect_port`],
//!   [`host_driver`], [`port`] and [`transport`];
//! * the host-side adapter registry and adapter execution, in
//!   [`runtime_adapters`]: which packaged adapters exist, what each of them
//!   declares, how a turn is admitted and dispatched to one of them, how the
//!   Agent's own report is normalized into this host's execution vocabulary,
//!   and the Subagent MCP mesh that reaches the same registry.
//! * the ACP session transport, in [`acp_driver_runtime`] and
//!   [`acp_session_transport`]: the shared ACP frame dialect's two protocol
//!   reducers and their machines, bounded process I/O, capability negotiation,
//!   the service-neutral process runtime, the driver-scoped persistent session
//!   pool with its approval parking and control, and the recorded-transcript
//!   replay arms for both reducers in `acp_driver_runtime::replay`;
//! * the local service control plane, in [`local_service`]: the target-neutral
//!   bounded HTTP/SSE transport, the detached-service lifecycle, and the
//!   active-turn and endpoint-lease registry the host's serve lanes reach;
//! * the thirteen Agent declarations as data, `resources/agent-conversation-drivers.json`,
//!   `resources/agent-native-capabilities.json` and `resources/agent-conversation-readiness.json`,
//!   embedded by [`runtime_adapters::registry`] because they are the registry's
//!   own input, and the two ACP session-protocol machines,
//!   `resources/state-machines/copilot.json` and
//!   `resources/state-machines/hermes.json`, compiled by `build.rs` for the
//!   reducers that replay them.
//!
//! What it does not own: any Agent's protocol. The per-Agent protocol adapter,
//! its driver execution and its frame parser arrive through the ports declared
//! in [`port`], in [`acp_driver_runtime::parser_port`] and in
//! `licoup-agent-adapter-sdk::port`; the composition above this crate supplies
//! them — `licoup-native` while the Agent crates do not exist,
//! `licoup-agent-<agent>` once they do — and the host's own lane reach arrives
//! the same way. The ACP dialogs this crate does hold are shared: the ACP
//! profile Copilot, OpenCode and Kilo Code all speak and the persistent ACP
//! profile Hermes speaks are framing and session semantics, not any one Agent's
//! protocol, and every per-Agent fact they read arrives through the port. No
//! Agent's protocol is implemented in this crate and nothing here is a vendor
//! branch.
//!
//! One seam here is a feature rather than `cfg(test)`: `test-support` carries
//! the ACP frame dialect a build with no composition reads, the reducer
//! vocabulary the host's Hermes suites drive, and the replay arms. It is a
//! feature because the host's own test build links this crate as a dependency,
//! and `cfg(test)` is false for a dependency — so a `cfg(test)` seam is compiled
//! out of exactly the build that calls it. The hermetic work-context fixtures
//! the host's integration suites drive are still host test material and stay
//! with the host.

