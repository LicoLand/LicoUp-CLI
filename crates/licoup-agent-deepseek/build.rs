//! Project the published `a4aa-dsh` card, launch spec and mechanism dialect
//! into the constants this package compiles against.
//!
//! This is a build-time bridge, not a second declaration. Every fact is read
//! from the published crate on every build, and the build fails when the card
//! stops carrying a fact this Agent's parser and transport depend on. The
//! dependency stays in the build graph so `a4aa`'s async ACP runtime feature set
//! neither replaces the client's synchronous transport pool nor changes the
//! client's `serde_json` ordering.

use a4aa::LaneSpec;
use a4aa::card::AgentSurface;
use a4aa::dialect::{CommandSurface, McpSurface, SubagentSurface};
use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::PathBuf;

fn main() {
    println!("cargo:rerun-if-changed=build.rs");

    let card = a4aa_dsh::card();
    let spec = a4aa_dsh::spec();
    let dialect = a4aa_dsh::dialect();

    let AgentSurface::Rpc(rpc) = &card.surface else {
        panic!("the published DeepSeek Harness card's primary lane is not RPC");
    };
    let LaneSpec::Rpc(_) = &spec.lane else {
        panic!("the published DeepSeek Harness spec does not materialize the RPC lane");
    };
    assert_eq!(
        card.id, dialect.id,
        "the card and its mechanism dialect disagree on the Agent id"
    );
    assert_eq!(
        spec.command.program, card.detect.binaries[0],
        "the launch program is not the detected binary"
    );

    let initialize = rpc
        .initialize
        .as_ref()
        .expect("the Harness card declares initialize")
        .method;
    let prompt = rpc.prompt.method;
    let shutdown = rpc
        .session_close
        .as_ref()
        .expect("the Harness card declares shutdown")
        .method;
    let text_event = rpc
        .text_event_method
        .expect("the Harness card declares the session event method");
    let completion = rpc
        .completion
        .as_ref()
        .expect("the Harness card declares session/status completion");
    let status = completion
        .status_value
        .expect("the Harness card declares the idle status value");
    let text_path = rpc
        .text_path
        .expect("the Harness card declares the assistant text path");
    // The card's path is relative to `params`; the parser reads it against the
    // whole frame, so the projection materializes the absolute JSON pointer.
    let text_pointer = format!(
        "/params/{}",
        text_path.split('.').collect::<Vec<_>>().join("/")
    );
    assert!(
        rpc.cancel.is_none(),
        "the published Harness card now declares a cancel call this package does not send"
    );
    assert!(
        rpc.session_open.is_none() && rpc.session_resume.is_none(),
        "the published Harness card now opens sessions; this package's pool assumes it does not"
    );
    // The card's model catalog describes the ACP alternate's `session/new`
    // config options; the SDK primary lane this package drives declares none.
    let _ = &card.features.models;

    let commands = match dialect.commands {
        CommandSurface::MarkdownDir(dir)
        | CommandSurface::PromptDir(dir)
        | CommandSurface::TomlDir(dir)
        | CommandSurface::SkillDir(dir) => Some(dir),
        CommandSurface::None => None,
    };
    let subagents = match dialect.subagents {
        SubagentSurface::MarkdownDir(dir)
        | SubagentSurface::CodexToml(dir)
        | SubagentSurface::KiroJson(dir) => Some(dir),
        SubagentSurface::None => None,
    };
    let (mcp_file, mcp_key, mcp_adapted) = match dialect.mcp {
        McpSurface::JsonMerge {
            file, key, adapted, ..
        } => (Some(file), Some(key), adapted),
        McpSurface::None => (None, None, false),
    };

    let mut generated = String::new();
    writeln!(
        generated,
        "// @generated by crates/licoup-agent-deepseek/build.rs from the published a4aa-dsh card."
    )
    .unwrap();
    writeln!(
        generated,
        "// Do not edit; edit the build projection instead."
    )
    .unwrap();
    macro_rules! string {
        ($name:literal, $value:expr) => {
            writeln!(generated, "pub const {}: &str = {:?};", $name, $value).unwrap();
        };
    }
    macro_rules! optional_string {
        ($name:literal, $value:expr) => {
            writeln!(
                generated,
                "pub const {}: Option<&str> = {:?};",
                $name, $value
            )
            .unwrap();
        };
    }
    macro_rules! boolean {
        ($name:literal, $value:expr) => {
            writeln!(generated, "pub const {}: bool = {:?};", $name, $value).unwrap();
        };
    }
    macro_rules! strings {
        ($name:literal, $values:expr) => {{
            write!(generated, "pub const {}: &[&str] = &[", $name).unwrap();
            for value in $values {
                write!(generated, "{value:?}, ").unwrap();
            }
            generated.push_str("];\n");
        }};
    }

    string!("UPSTREAM_CARD_ID", card.id);
    string!("UPSTREAM_CARD_LABEL", card.label);
    string!("UPSTREAM_PROGRAM", spec.command.program);
    strings!(
        "UPSTREAM_LAUNCH_ARGS",
        spec.command.args.iter().map(String::as_str)
    );
    string!("UPSTREAM_LANE_KIND", "rpc");
    strings!("UPSTREAM_PERMISSION_MODES", card.features.permission_modes);
    optional_string!(
        "UPSTREAM_PERMISSION_DEFAULT",
        card.features.permission_default
    );
    optional_string!("UPSTREAM_SKILLS_DIR", dialect.skills_dir);
    optional_string!(
        "UPSTREAM_RULES_FILE",
        dialect.rules.as_ref().map(|target| target.path)
    );
    optional_string!("UPSTREAM_COMMANDS_DIR", commands);
    optional_string!("UPSTREAM_SUBAGENTS_DIR", subagents);
    optional_string!("UPSTREAM_MCP_FILE", mcp_file);
    optional_string!("UPSTREAM_MCP_KEY", mcp_key);
    boolean!("UPSTREAM_MCP_ADAPTED", mcp_adapted);
    boolean!("UPSTREAM_NATIVE_PROFILES", dialect.native_profiles);

    string!("UPSTREAM_INITIALIZE_METHOD", initialize);
    string!("UPSTREAM_PROMPT_METHOD", prompt);
    string!("UPSTREAM_SHUTDOWN_METHOD", shutdown);
    string!("UPSTREAM_TEXT_EVENT_METHOD", text_event);
    string!("UPSTREAM_COMPLETION_METHOD", completion.method);
    string!("UPSTREAM_COMPLETION_STATUS", status);
    string!("UPSTREAM_TEXT_PATH", text_path);
    string!("UPSTREAM_TEXT_POINTER", text_pointer);
    boolean!("UPSTREAM_HAS_CANCEL", rpc.cancel.is_some());
    string!(
        "UPSTREAM_SESSION_SCOPE",
        format!("{:?}", rpc.session_scope).to_lowercase()
    );

    let out = PathBuf::from(env::var_os("OUT_DIR").expect("cargo sets OUT_DIR"));
    fs::write(out.join("deepseek_dialect.rs"), generated)
        .expect("write generated DeepSeek Harness dialect facts");
}
