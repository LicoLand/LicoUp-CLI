const nativeBinaryCheck = (binary, features = []) => {
  const args = ["check", "--manifest-path", NATIVE_MANIFEST, "--bin", binary];
  if (features.length > 0) {
    args.push("--features", features.join(","));
  }
  return command("cargo", args, 10 * 60_000);
};

